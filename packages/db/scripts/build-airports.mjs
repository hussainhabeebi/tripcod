#!/usr/bin/env node
// Builds the world airport list from OurAirports (public domain data).
//
//   node packages/db/scripts/build-airports.mjs [airports.csv] [countries.csv]
//
// With no arguments the CSVs are downloaded from the OurAirports data mirror.
// Writes:
//   apps/api/d1/airports/seed.sql   — INSERT statements for the D1 `airports` table
//   apps/api/src/data/airports.json — compact copy bundled in the API Worker as a
//                                     fallback when D1 is unavailable
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const SRC = "https://raw.githubusercontent.com/davidmegginson/ourairports-data/main";

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (ch !== "\r") field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.filter((r) => r.length === head.length).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

async function load(arg, name) {
  if (arg) return readFile(arg, "utf8");
  const res = await fetch(`${SRC}/${name}`);
  if (!res.ok) throw new Error(`Download of ${name} failed: ${res.status}`);
  return res.text();
}

// Names travellers in our markets actually type. OurAirports uses e.g. "Calicut"
// and "Vasco da Gama"; the old/alternative names go into keywords so both match.
const CITY_OVERRIDES = { CCJ: "Kozhikode", GOI: "Goa", GOX: "Goa", DWC: "Dubai", TRV: "Thiruvananthapuram" };
const EXTRA_KEYWORDS = {
  CCJ: "Calicut", COK: "Cochin, Ernakulam", TRV: "Trivandrum", BOM: "Bombay", MAA: "Madras",
  BLR: "Bangalore", CCU: "Calcutta", IXE: "Mangalore", PNQ: "Poona", GOI: "Dabolim, Vasco da Gama",
  GOX: "Mopa, North Goa", DWC: "Al Maktoum, Jebel Ali, Dubai World Central", IXZ: "Port Blair",
};

const RANK = { large_airport: 3, medium_airport: 2, small_airport: 1, seaplane_base: 1 };

const [airportsCsv, countriesCsv] = await Promise.all([load(process.argv[2], "airports.csv"), load(process.argv[3], "countries.csv")]);
const countries = Object.fromEntries(parseCsv(countriesCsv).map((c) => [c.code, c.name]));

const byCode = new Map();
for (const a of parseCsv(airportsCsv)) {
  const code = a.iata_code?.trim().toUpperCase();
  if (!code || !/^[A-Z]{3}$/.test(code)) continue;
  const rank = RANK[a.type];
  if (!rank) continue;                                              // closed, heliport, balloonport
  if (rank === 1 && a.scheduled_service !== "yes") continue;        // small fields without airline service
  const row = {
    code,
    name: a.name.trim(),
    city: CITY_OVERRIDES[code] ?? (a.municipality || a.name).trim(),
    country: a.iso_country,
    countryName: countries[a.iso_country] ?? a.iso_country,
    lat: Math.round(Number(a.latitude_deg) * 1e4) / 1e4,
    lon: Math.round(Number(a.longitude_deg) * 1e4) / 1e4,
    rank: rank + (a.scheduled_service === "yes" ? 1 : 0),
    keywords: [EXTRA_KEYWORDS[code], a.keywords].filter(Boolean).join(", ").trim(),
  };
  const prev = byCode.get(code);
  if (!prev || row.rank > prev.rank) byCode.set(code, row);         // OurAirports has a few duplicate IATA codes
}

const airports = [...byCode.values()].sort((x, y) => y.rank - x.rank || x.code.localeCompare(y.code));

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const lines = [
  "-- Generated by packages/db/scripts/build-airports.mjs from OurAirports (public domain).",
  "-- Apply with: pnpm --filter @tripcod/api d1:airports",
  "DELETE FROM airports;",
];
for (let i = 0; i < airports.length; i += 200) {
  const chunk = airports.slice(i, i + 200).map((a) =>
    `(${q(a.code)},${q(a.name)},${q(a.city)},${q(a.country)},${q(a.countryName)},${a.lat},${a.lon},${a.rank},${q(a.keywords)})`);
  lines.push(`INSERT INTO airports (code,name,city,country,country_name,lat,lon,rank,keywords) VALUES\n${chunk.join(",\n")};`);
}

await mkdir(resolve(ROOT, "apps/api/d1/airports"), { recursive: true });
await mkdir(resolve(ROOT, "apps/api/src/data"), { recursive: true });
await writeFile(resolve(ROOT, "apps/api/d1/airports/seed.sql"), lines.join("\n") + "\n");
// Compact tuple form for the bundled fallback: [code, name, city, country, countryName, rank, keywords?]
await writeFile(resolve(ROOT, "apps/api/src/data/airports.json"),
  JSON.stringify(airports.map((a) => {
    const row = [a.code, a.name, a.city, a.country, a.countryName, a.rank];
    return a.keywords ? [...row, a.keywords] : row;
  })));
console.log(`Wrote ${airports.length} airports`);
